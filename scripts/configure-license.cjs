const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const envPath = path.join(root, '.env');
if (fs.existsSync(envPath)) process.loadEnvFile(envPath);
const output = path.join(root, 'src', 'app', 'primeui-license.ts');
const content = '// Generated by scripts/configure-license.cjs. Do not commit.\nexport const primeUiLicense = ' + JSON.stringify(process.env.PRIMEUI_LICENSE || '') + ';\n';
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) fs.writeFileSync(output, content);
